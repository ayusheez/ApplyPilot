const assert = require('node:assert/strict');
const api = require('../.stage1-test-build/api.js');
const { today, daysUntil } = require('../.stage1-test-build/format.js');
const { runDemoAnalysis } = require('../.stage1-test-build/demo-analysis.js');
(async () => {
 let checks = 0;
 const ok = (v) => { assert.ok(v); checks++; };
 const start = await api.listApplications();
 const a = await api.createApplication({company:' QA Company ',role:'Engineer',status:'Applied',appliedOn:today(),notes:''});
 ok(a.company === 'QA Company');
 ok((await api.listApplications()).length === start.length + 1);
 const edited = await api.updateApplication(a.id,{status:'Interview',notes:'Prepare',interviewDate:today()});
 ok(edited.status === 'Interview' && edited.timeline.some(t=>t.type==='status') && edited.timeline.some(t=>t.type==='note'));
 ok(daysUntil(today()) === 0 && daysUntil(today()+'T12:00:00') === 0);
 const email={subject:'Application confirmation',body:'Thank you for applying to Sample Labs for the Backend Engineer role. We received your application.'};
 const res = await api.analyseEmail(email); ok(res.kind === 'result');
 const req={email,fields:{company:'Sample Labs',role:'Backend Engineer',status:'Applied'},targetApplicationId:null};
 const imported=await api.saveImport(req); ok(imported.sourceEmails.length === 1);
 ok((await api.analyseEmail(email)).kind === 'duplicate');
 await assert.rejects(api.saveImport(req), /already imported/); checks++;
 const updateEmail={subject:'Interview update',body:'We invite you to an interview for the Backend Engineer role at Sample Labs.'};
 const updated=await api.saveImport({email:updateEmail,fields:{company:'Sample Labs Updated',role:'Backend Engineer II',status:'Interview'},targetApplicationId:imported.id});
 ok(updated.company === 'Sample Labs Updated' && updated.role === 'Backend Engineer II' && updated.sourceEmails.length === 2);
 const invalid=runDemoAnalysis({subject:'Interview',body:'Your interview on 31 February 2026 is planned.'},[]); ok(invalid.interviewDate.value === null);
 const wrongRole=runDemoAnalysis(email,[{...imported,role:'Designer'}]); ok(wrongRole.matchedApplicationId === null);
 await api.deleteApplication(a.id); ok(await api.getApplication(a.id) === null);
 await api.deleteApplication(imported.id); ok((await api.listApplications()).length === start.length);
 console.log(`${checks} regression checks passed: CRUD, timeline, trimming, dates, import, duplicate protection, corrected fields and role matching.`);
})().catch(e=>{console.error(e);process.exitCode=1;});
